_ACTIVE = STRINGS.get(LANGUAGE, STRINGS["en"])


def current_language() -> str:
    override = _LANGUAGE_OVERRIDE.get()
    if override in STRINGS:
        return override
    return next(code for code, table in STRINGS.items() if table is _ACTIVE)


@contextmanager
def language_context(code: str) -> Iterator[None]:
    """Temporarily override the UI language in the current async context."""
    token = _LANGUAGE_OVERRIDE.set(code if code in STRINGS else None)
    try:
        yield
    finally:
        _LANGUAGE_OVERRIDE.reset(token)


def set_language(code: str) -> None:
    """Switch the UI language for this process; callers rebuild their controls."""
    global _ACTIVE
    _ACTIVE = STRINGS.get(code, _ACTIVE)


def get_string(key: str, **kwargs: object) -> str:
    text = STRINGS[current_language()].get(key) or STRINGS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except KeyError:
            return text
    return text
